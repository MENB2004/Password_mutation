# ==============================================================================

@dataclass
class BatchValidationResult:
    """Validation report evaluated on a controlled batch of generator outputs."""
    batch_size: int
    configured_length: int
    configured_alphabet_size: int
    total_characters_evaluated: int
    tests: List[DiagnosticTest] = field(default_factory=list)
    passed_count: int = 0
    failed_count: int = 0
    not_applicable_count: int = 0
    empirical_entropy_per_char: float = 0.0
    theoretical_entropy_per_char: float = 0.0
    entropy_efficiency_ratio: float = 0.0


def validate_generator_batch(config: Optional[GeneratorConfig] = None,
                             batch_size: int = 100) -> BatchValidationResult:
    """Validate generator implementation behavior across a controlled batch of samples.

    Evaluates:
    1. Strict alphabet containment (100% of characters belong to configured pool).
    2. Strict length enforcement (100% of generated passwords have requested length).
    3. Aggregate character frequency Chi-Square goodness-of-fit against uniform distribution.
    4. Positional class concentration (checks for fixed template biases across positions).
    5. Empirical Shannon entropy per character vs theoretical log2(N).
    """
    if config is None:
        config = GeneratorConfig()

    config.validate()
    pool = config.get_character_pool()
    pool_set = set(pool)
    alphabet_size = len(pool)
    tests: List[DiagnosticTest] = []

    # Generate batch
    batch = [generate_secure_password(config).password for _ in range(batch_size)]
    total_chars = batch_size * config.length

    # 1. Length & Alphabet Containment
    all_correct_length = all(len(pw) == config.length for pw in batch)
    all_allowed_chars = all(all(c in pool_set for c in pw) for pw in batch)

    tests.append(
        DiagnosticTest(
            test_name="Alphabet & Length Enforcement",
            status="Passed" if (all_correct_length and all_allowed_chars) else "Failed",
            observed_value=f"{batch_size}/{batch_size} exact length {config.length}, 0 disallowed chars",
            threshold_criteria="100% of samples match exact length and contain only allowed pool characters.",
            what_it_detects="Detects length truncation, buffer overruns, or character pool contamination.",
            what_it_cannot_establish="Does not evaluate statistical distribution across allowed characters.",
        )
    )

    # 2. Chi-Square Uniformity Test across aggregate characters
    char_counts: Dict[str, int] = {c: 0 for c in pool}
    for pw in batch:
        for c in pw:
            char_counts[c] += 1

    expected_per_char = total_chars / alphabet_size
    if expected_per_char >= 5.0:
        chi2_stat = sum(((char_counts[c] - expected_per_char) ** 2) / expected_per_char for c in pool)
        # Approximate 99% critical value using Wilson-Hilferty transformation for large degrees of freedom
        df = alphabet_size - 1
        # Wilson-Hilferty approximation for Chi-Square critical value at alpha=0.01 (z_0.01 = 2.3263)
        z_crit = 2.3263
        chi2_crit = df * ((1 - 2.0 / (9.0 * df) + z_crit * math.sqrt(2.0 / (9.0 * df))) ** 3)
        chi2_passed = chi2_stat <= chi2_crit
        chi2_status = "Passed" if chi2_passed else "Failed"
        chi2_observed = f"chi2 = {chi2_stat:.2f} (df={df}, critical={chi2_crit:.2f}, E={expected_per_char:.1f})"
        chi2_crit_text = f"chi2 <= critical threshold ({chi2_crit:.2f}) at alpha=0.01 significance."
    else:
        chi2_status = "Not applicable"
        chi2_observed = f"Expected count E = {expected_per_char:.2f} < 5.0"
        chi2_crit_text = f"Requires total characters >= {5 * alphabet_size} (increase batch size or length)."

    tests.append(
        DiagnosticTest(
            test_name="Aggregate Chi-Square Uniformity Test",
            status=chi2_status,
            observed_value=chi2_observed,
            threshold_criteria=chi2_crit_text,
            what_it_detects="Detects frequency skew or bias favoring particular characters in the CSPRNG.",
            what_it_cannot_establish="Does not prove lack of serial autocorrelation or seed reproducibility.",
        )
    )

    # 3. Positional Class Concentration (Template Bias Check)
    # Check if any position has > 90% concentration in a single character class when multiple classes are enabled
    classes_enabled_count = sum([config.use_lowercase, config.use_uppercase, config.use_digits, config.use_symbols])
    positional_bias_found = False
    worst_pos_concentration = 0.0

    if classes_enabled_count > 1 and batch_size >= 30:
        for pos in range(config.length):
            chars_at_pos = [pw[pos] for pw in batch]
            pos_classes = {
                "lower": sum(1 for c in chars_at_pos if c.islower()),
                "upper": sum(1 for c in chars_at_pos if c.isupper()),
                "digit": sum(1 for c in chars_at_pos if c.isdigit()),
                "symbol": sum(1 for c in chars_at_pos if c in string.punctuation or not c.isalnum()),
            }
            max_class_at_pos = max(pos_classes.values()) / batch_size
            worst_pos_concentration = max(worst_pos_concentration, max_class_at_pos)
            if max_class_at_pos >= 0.90:
                positional_bias_found = True

        pos_status = "Failed" if positional_bias_found else "Passed"
        pos_obs = f"Max class concentration at any position = {worst_pos_concentration:.1%}"
        pos_crit = "< 90% class concentration at any position across batch (uniform positional drawing)."
    else:
        pos_status = "Not applicable"
        pos_obs = "Only 1 character class enabled or batch size < 30"
        pos_crit = "Requires >= 2 character classes and batch size >= 30."

    tests.append(
        DiagnosticTest(
            test_name="Positional Class Concentration (Template Bias)",
            status=pos_status,
            observed_value=pos_obs,
            threshold_criteria=pos_crit,
            what_it_detects="Detects structured templates (e.g. fixed TitleCase at index 0 or digits at the end).",
            what_it_cannot_establish="Cannot detect non-class specific positional dependencies.",
        )
    )

    # 4. Empirical Shannon Entropy per Character
    empirical_h = 0.0
    for count in char_counts.values():
        if count > 0:
            p = count / total_chars
            empirical_h -= p * math.log2(p)

    theoretical_h = math.log2(alphabet_size)
    efficiency_ratio = empirical_h / theoretical_h if theoretical_h > 0 else 0.0
    entropy_passed = efficiency_ratio >= 0.95

    tests.append(
        DiagnosticTest(
            test_name="Empirical Shannon Entropy Ratio",
            status="Passed" if entropy_passed else "Failed",
            observed_value=f"H_emp = {empirical_h:.3f} bits/char ({efficiency_ratio:.2%} of theoretical)",
            threshold_criteria=f">= 95.0% of theoretical maximum (log2({alphabet_size}) = {theoretical_h:.3f} bits)",
            what_it_detects="Measures empirical information density of character distribution.",
            what_it_cannot_establish="Does not measure cryptographic computational hardness against cracking.",
        )
    )

    passed_count = sum(1 for t in tests if t.status == "Passed")
    failed_count = sum(1 for t in tests if t.status == "Failed")
    na_count = sum(1 for t in tests if t.status == "Not applicable")

    return BatchValidationResult(
        batch_size=batch_size,
        configured_length=config.length,
        configured_alphabet_size=alphabet_size,
        total_characters_evaluated=total_chars,
        tests=tests,
        passed_count=passed_count,
        failed_count=failed_count,
        not_applicable_count=na_count,
        empirical_entropy_per_char=empirical_h,
        theoretical_entropy_per_char=theoretical_h,
        entropy_efficiency_ratio=efficiency_ratio,
    )



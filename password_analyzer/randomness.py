# 4. QUALIFIED OVERALL RANDOMNESS ASSESSMENT BUILDER
# ==============================================================================

@dataclass
class QualifiedAssessment:
    """Transparent summary distinguishing entropy, patterns, statistical tests, and provenance."""
    theoretical_entropy_bits: float
    theoretical_entropy_label: str
    dictionary_finding: str
    structural_finding: str
    statistical_summary: str
    generation_provenance: str
    generation_assurance: str
    qualified_summary: str
    scientific_limitations: List[str]


def build_qualified_randomness_assessment(password: str,
                                         is_generated: bool = False,
                                         dictionary_base: Optional[str] = None,
                                         mutations: Optional[List[str]] = None,
                                         assumed_pool: int = 94,
                                         diagnostics: Optional[StatisticalDiagnosticResult] = None) -> QualifiedAssessment:
    """Construct a scientifically defensible qualified assessment.

    Follows the strict mandate: Never label an arbitrary password 'Proven Random'
    or 'Guaranteed Secure'. Distinguishes theoretical entropy, pattern detection,
    statistical diagnostics, and generation provenance.
    """
    length = len(password)
    h_theoretical = length * math.log2(max(1, assumed_pool))
    entropy_label = f"{h_theoretical:.2f} bits (assuming uniform independent drawing from N={assumed_pool})"

    # Dictionary findings
    if dictionary_base:
        dict_finding = f"Dictionary root '{dictionary_base}' detected with associated predictable mutation rules."
    else:
        dict_finding = "No supported dictionary root detected under the active dictionary wordlist."

    # Structural findings
    mutations_list = mutations or []
    structural_muts = [m for m in mutations_list if m in ("sequential characters", "repetitive characters", "keyboard sequence")]
    if structural_muts:
        struct_finding = f"Non-dictionary structural patterns detected: {', '.join(structural_muts)}."
    else:
        struct_finding = "No non-dictionary structural runs (sequential, repetitive, or keyboard patterns) detected."

    # Statistical findings
    if diagnostics:
        stat_summary = (
            f"{diagnostics.passed_count} passed, {diagnostics.failed_count} failed, "
            f"{diagnostics.not_applicable_count} not applicable (sample length L = {length})."
        )
    else:
        stat_summary = "Statistical diagnostics not executed."

    # Provenance
    if is_generated:
        prov = PROVENANCE_GENERATED
        assur = ASSURANCE_GENERATED
        qual_summary = (
            f"This password was generated using Python's cryptographically secure 'secrets' module (CSPRNG) "
            f"over a configured alphabet of {assumed_pool} characters. Theoretical character-pool entropy is "
            f"{h_theoretical:.2f} bits under uniform independent drawing. While the generation process utilizes "
            f"the operating system's cryptographic entropy source, visual appearance alone cannot prove physical randomness."
        )
    else:
        prov = PROVENANCE_USER_ENTERED
        assur = ASSURANCE_USER_ENTERED
        if not dictionary_base and not structural_muts:
            qual_summary = (
                f"No supported dictionary or structural patterns were detected by the current analysis rules. "
                f"The theoretical character-pool entropy ({h_theoretical:.2f} bits) is calculated under an idealized "
                f"uniform independent-selection assumption (N={assumed_pool}). The password's generation process is "
                f"unknown, so actual randomness cannot be verified from the entered string alone."
            )
        else:
            qual_summary = (
                f"Predictable patterns were identified ({dict_finding} {struct_finding}). "
                f"Even if theoretical character-pool entropy is {h_theoretical:.2f} bits, detected predictable features "
                f"substantially degrade search space complexity under targeted guessing attacks."
            )

    limitations = [
        "Theoretical entropy (H = L * log2(N)) assumes independent and uniform selection; it is an upper bound and not measured randomness.",
        "A string that appears visually disordered may still originate from a compromised generator, predictable formula, or breach corpus.",
        "Passing statistical diagnostics does not prove true physical randomness or security against targeted dictionary/rule attacks.",
        "Source-code inspection of secrets.choice() confirms CSPRNG API usage but cannot prove physical hardware entropy source health.",
    ]

    return QualifiedAssessment(
        theoretical_entropy_bits=h_theoretical,
        theoretical_entropy_label=entropy_label,
        dictionary_finding=dict_finding,
        structural_finding=struct_finding,
        statistical_summary=stat_summary,
        generation_provenance=prov,
        generation_assurance=assur,
        qualified_summary=qual_summary,
        scientific_limitations=limitations,
    )

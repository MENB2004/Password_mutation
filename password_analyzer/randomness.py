# 2. STATISTICAL DIAGNOSTICS FOR SINGLE PASSWORDS & BATCHES
# ==============================================================================

@dataclass
class DiagnosticTest:
    """Single diagnostic test outcome with scientific scope and limitations."""
    test_name: str
    status: str                         # 'Passed', 'Failed', or 'Not applicable'
    observed_value: str
    threshold_criteria: str
    what_it_detects: str
    what_it_cannot_establish: str


@dataclass
class StatisticalDiagnosticResult:
    """Aggregate result of statistical diagnostics evaluated on a sample."""
    sample_type: str                   # 'Single Password' or 'Controlled Batch'
    sample_size: int                   # Number of characters or passwords
    tests: List[DiagnosticTest] = field(default_factory=list)
    passed_count: int = 0
    failed_count: int = 0
    not_applicable_count: int = 0
    methodological_note: str = ""


def assess_single_password_randomness(password: str, assumed_pool_size: Optional[int] = None) -> StatisticalDiagnosticResult:
    """Evaluate scientifically grounded statistical diagnostics on a single password.

    Pre-condition checks ensure tests requiring asymptotic sample sizes
    (e.g. Pearson Chi-Square goodness-of-fit) are marked 'Not applicable'
    rather than returning mathematically invalid false positives or false negatives.
    """
    tests: List[DiagnosticTest] = []
    length = len(password)

    if length == 0:
        return StatisticalDiagnosticResult(
            sample_type="Single Password",
            sample_size=0,
            tests=[
                DiagnosticTest(
                    test_name="Input Length Check",
                    status="Failed",
                    observed_value="0 characters",
                    threshold_criteria="Length >= 1",
                    what_it_detects="Identifies empty or missing inputs.",
                    what_it_cannot_establish="Does not evaluate randomness.",
                )
            ],
            failed_count=1,
            methodological_note="Empty input cannot be evaluated for randomness.",
        )

    # 1. Character Class Diversity Test
    classes_present = []
    if any(c.islower() for c in password):
        classes_present.append("lowercase")
    if any(c.isupper() for c in password):
        classes_present.append("uppercase")
    if any(c.isdigit() for c in password):
        classes_present.append("digits")
    if any(c in string.punctuation or not c.isalnum() for c in password):
        classes_present.append("symbols")

    num_classes = len(classes_present)
    if length < 8:
        class_status = "Not applicable"
        class_criteria = "Sample too short (L < 8) for reliable class diversity inference."
    elif num_classes >= 3:
        class_status = "Passed"
        class_criteria = ">= 3 distinct character classes observed for L >= 8."
    elif num_classes >= 2:
        class_status = "Passed"
        class_criteria = ">= 2 character classes observed for L >= 8."
    else:
        class_status = "Failed"
        class_criteria = ">= 2 character classes expected; only 1 class detected."

    tests.append(
        DiagnosticTest(
            test_name="Character Class Diversity",
            status=class_status,
            observed_value=f"{num_classes}/4 classes ({', '.join(classes_present)})",
            threshold_criteria=class_criteria,
            what_it_detects="Detects single-class restrictions (e.g. all-lowercase or all-digits).",
            what_it_cannot_establish="Cannot prove that characters within present classes were drawn uniformly.",
        )
    )

    # 2. Maximum Consecutive Repetition Run Length
    max_run = 1
    current_run = 1
    for i in range(1, length):
        if password[i] == password[i - 1]:
            current_run += 1
            max_run = max(max_run, current_run)
        else:
            current_run = 1

    if length < 4:
        run_status = "Not applicable"
        run_crit = "Sample length L < 4 is insufficient for repetition run inference."
    elif max_run >= 4 or (length >= 6 and max_run / length >= 0.5):
        run_status = "Failed"
        run_crit = "Max consecutive identical run < 4 characters and < 50% total length."
    else:
        run_status = "Passed"
        run_crit = "Max consecutive identical run < 4 characters."

    tests.append(
        DiagnosticTest(
            test_name="Maximum Consecutive Identical Run",
            status=run_status,
            observed_value=f"Max run = {max_run} identical character{'s' if max_run > 1 else ''}",
            threshold_criteria=run_crit,
            what_it_detects="Detects repeated identical runs (e.g. 'aaaa', '1111') that deviate from uniform drawing.",
            what_it_cannot_establish="Cannot detect non-adjacent repetitions or patterned interleaving (e.g. 'ababab').",
        )
    )

    # 3. Distinct Character Ratio (Uniqueness Ratio)
    unique_count = len(set(password))
    uniqueness_ratio = unique_count / length

    if length < 6:
        uniq_status = "Not applicable"
        uniq_crit = "Sample length L < 6 is insufficient for uniqueness ratio inference."
    elif uniqueness_ratio < 0.40:
        uniq_status = "Failed"
        uniq_crit = "Distinct character ratio >= 0.40 for L >= 6."
    else:
        uniq_status = "Passed"
        uniq_crit = "Distinct character ratio >= 0.40 for L >= 6."

    tests.append(
        DiagnosticTest(
            test_name="Distinct Character Uniqueness Ratio",
            status=uniq_status,
            observed_value=f"{unique_count}/{length} unique ({uniqueness_ratio:.2%})",
            threshold_criteria=uniq_crit,
            what_it_detects="Detects severe character repetition and low-entropy pools.",
            what_it_cannot_establish="Cannot evaluate spatial distribution, ordering, or positional independence.",
        )
    )

    # 4. Pearson Chi-Square Uniformity Test across Character Alphabet
    # Under standard statistical theory, Pearson's Chi-Square test requires expected count E_i >= 5 per bin.
    # For a character pool N in [26, 94], this requires minimum length L >= 5 * N (130 to 470 characters).
    pool_size = assumed_pool_size if assumed_pool_size and assumed_pool_size > 0 else 94
    min_required_len = 5 * pool_size
    tests.append(
        DiagnosticTest(
            test_name="Pearson Chi-Square Uniformity Test",
            status="Not applicable",
            observed_value=f"Length L = {length} characters",
            threshold_criteria=f"Requires L >= {min_required_len} (E_i >= 5 across N={pool_size} alphabet bins)",
            what_it_detects="Tests goodness-of-fit against a discrete uniform distribution over the full alphabet.",
            what_it_cannot_establish=(
                "Statistically invalid on single short strings due to expected frequency underflow (E_i < 5). "
                "Must be evaluated across a batch or long bitstream."
            ),
        )
    )

    # 5. Position-Specific Independence Analysis
    tests.append(
        DiagnosticTest(
            test_name="Position-Specific Independence Test",
            status="Not applicable",
            observed_value="Single string instance (sample count n = 1)",
            threshold_criteria="Requires multi-sample batch (n >= 50) generated under identical configuration",
            what_it_detects="Detects position-dependent generator templates (e.g. fixed uppercase at index 0).",
            what_it_cannot_establish="Cannot be computed from a single password instance without multiple draws.",
        )
    )

    passed_count = sum(1 for t in tests if t.status == "Passed")
    failed_count = sum(1 for t in tests if t.status == "Failed")
    na_count = sum(1 for t in tests if t.status == "Not applicable")

    note = (
        "Statistical tests on a single short password can only identify gross structural anomalies "
        "(e.g. single-class restrictions or excessive runs). Asymptotic tests (Chi-Square goodness-of-fit) "
        "are intentionally marked 'Not applicable' to prevent mathematically invalid conclusions."
    )

    return StatisticalDiagnosticResult(
        sample_type="Single Password",
        sample_size=length,
        tests=tests,
        passed_count=passed_count,
        failed_count=failed_count,
        not_applicable_count=na_count,
        methodological_note=note,
    )



# 1. CSPRNG PASSWORD GENERATOR
# ==============================================================================

@dataclass(frozen=True)
class GeneratorConfig:
    """Configuration for cryptographically secure password generation."""
    length: int = 16
    use_lowercase: bool = True
    use_uppercase: bool = True
    use_digits: bool = True
    use_symbols: bool = True
    custom_symbols: str = "!@#$%^&*()_+-=[]{}|;:,.<>?"

    def get_character_pool(self) -> str:
        """Construct the configured alphabet and validate non-emptiness."""
        chars = ""
        if self.use_lowercase:
            chars += string.ascii_lowercase
        if self.use_uppercase:
            chars += string.ascii_uppercase
        if self.use_digits:
            chars += string.digits
        if self.use_symbols:
            chars += self.custom_symbols

        # Deduplicate while preserving order
        seen = set()
        deduped = []
        for c in chars:
            if c not in seen:
                seen.add(c)
                deduped.append(c)
        return "".join(deduped)

    def validate(self) -> None:
        """Validate generator configuration constraints."""
        if self.length < 1:
            raise ValueError(f"Password length must be at least 1 (got {self.length}).")
        if self.length > 512:
            raise ValueError(f"Password length cannot exceed 512 characters (got {self.length}).")
        pool = self.get_character_pool()
        if not pool:
            raise ValueError("At least one character class must be selected for password generation.")


@dataclass
class GenerationResult:
    """Output of a cryptographically secure generation request."""
    password: str
    length: int
    alphabet_size: int
    alphabet_characters: str
    theoretical_entropy_bits: float
    active_character_classes: List[str]
    generation_method: str = PROVENANCE_GENERATED
    generation_assurance: str = ASSURANCE_GENERATED
    method_explanation: str = METHOD_DESCRIPTION_GENERATED
    is_generated: bool = True


def calculate_configured_entropy(length: int, alphabet_size: int) -> float:
    """Calculate theoretical character-pool entropy: H = L * log2(N)."""
    if length <= 0 or alphabet_size <= 0:
        return 0.0
    return length * math.log2(alphabet_size)


def generate_secure_password(config: Optional[GeneratorConfig] = None) -> GenerationResult:
    """Generate a password using Python's cryptographically secure secrets module.

    Uses secrets.choice() over the configured alphabet, guaranteeing uniform
    drawing from the OS cryptographic pseudorandom number generator without
    using the insecure random module.
    """
    if config is None:
        config = GeneratorConfig()

    config.validate()
    pool = config.get_character_pool()
    alphabet_size = len(pool)

    # Cryptographically secure character selection
    chosen_chars = [secrets.choice(pool) for _ in range(config.length)]
    password = "".join(chosen_chars)

    classes = []
    if config.use_lowercase:
        classes.append("lowercase (a-z)")
    if config.use_uppercase:
        classes.append("uppercase (A-Z)")
    if config.use_digits:
        classes.append("digits (0-9)")
    if config.use_symbols:
        classes.append("symbols/punctuation")

    entropy_bits = calculate_configured_entropy(config.length, alphabet_size)

    return GenerationResult(
        password=password,
        length=config.length,
        alphabet_size=alphabet_size,
        alphabet_characters=pool,
        theoretical_entropy_bits=entropy_bits,
        active_character_classes=classes,
    )


